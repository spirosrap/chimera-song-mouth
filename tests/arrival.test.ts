import {test,expect,spyOn} from 'bun:test';
import {readFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import * as THREE from 'three';
import {validateScene,sceneCue,sceneCamera,type CameraView} from '../src/scene/scene.ts';
import {movieScene} from '../src/scene/library.ts';
import {arrivalPose,arrivalCamera} from '../src/scene/arrival.ts';
import type {DialoguePerformance} from '../src/scene/dialogue.ts';
import {TeleTrack} from '../src/show/tele.ts';
import {initEngine} from './harness.ts';
await initEngine();
const {ArrivalField}=await import('../src/ui/render/arrival.ts');
const {VoiceModel}=await import('../src/ui/analysis.ts');
const {planDialoguePart}=await import('../src/scene/dialogue.ts');
const file=(name:string)=>readFileSync(new URL(`../public/scenes/arrival/${name}`,import.meta.url));
const scene=validateScene(JSON.parse(file('scene.json').toString()));
const score:DialoguePerformance=JSON.parse(file('performance.json').toString());
const raw=gunzipSync(file('ian.tele.gz')),track=new TeleTrack(raw.buffer.slice(raw.byteOffset,raw.byteOffset+raw.byteLength));

test('Arrival preserves the complete supplied clip with one speaker and a separate listener camera',()=>{
 expect(movieScene('arrival')).toBeDefined();expect(scene.setting).toBe('arrival');
 expect(scene.duration).toBeGreaterThan(29.3);expect(scene.duration).toBeLessThan(30);
 expect(scene.characters.map(c=>c.id)).toEqual(['ian']);expect(scene.cues).toHaveLength(4);
 expect(score.lines.flatMap(l=>l.words)).toHaveLength(33);
 expect(file('mix.mp3').length).toBeGreaterThan(800_000);expect(file('backing.mp3').length).toBeGreaterThan(800_000);
 expect(()=>validateScene({...scene,characters:[]})).toThrow('incomplete');
 expect(()=>validateScene({...scene,setting:'press'})).toThrow('character');
 expect(()=>validateScene({...scene,shots:[{time:0,view:'father'}]})).toThrow('camera');
});

test('the quiet closing line starts at its real articulation, after the original hesitation',()=>{
 const line=score.lines.at(-1)!;expect(line.text).toBe('It was meeting you.');
 expect(line.start).toBeGreaterThan(22.8);expect(line.start).toBeLessThan(23.05);
 expect(line.end).toBeLessThan(25.1);expect(sceneCue(scene,22)).toBeUndefined();
 expect(sceneCue(scene,23.3)?.text).toBe('It was meeting you.');
 expect(sceneCamera(scene,6,'auto')).toBe('ian');expect(sceneCamera(scene,27,'auto')).toBe('louise');
 expect(sceneCamera(scene,27,'wide')).toBe('wide');
 for(const t of [0,3.8,15,19,21,22.5,27,29]){
  expect(sceneCue(scene,t)).toBeUndefined();const msg=track.message(track.indexAt(t)).t;
  expect(msg.gate).toBeLessThan(.01);expect(msg.outRms).toBeLessThan(.00001);
 }
});

test('all four phrases are generated by physical articulation on the full source clock',()=>{
 const part=score.parts[0];expect(part.kind).toBe('voice');expect(part.recordingType).toBeUndefined();expect(part.effects).toBeUndefined();
 const plan=planDialoguePart(score,'ian');expect(plan.length).toBeGreaterThan(200);expect(plan.length).toBeLessThan(1000);
 expect(plan.some(g=>g.targets.lipAp!==undefined&&g.targets.lipAp<0)).toBe(true);
 expect(plan.some(g=>g.targets.abduction!==undefined&&g.targets.abduction>0)).toBe(true);
 expect(track.duration).toBeCloseTo(scene.duration,1);expect(track.body.female).toBeCloseTo(part.body.female,6);
 for(const [i,line] of score.lines.entries()){
  expect(line.segments.filter(s=>s.wordEnd)).toHaveLength(line.words.length);expect(line.end).toBeLessThan(score.lines[i+1]?.start??scene.duration);
  let peak=0;for(let f=track.indexAt(line.start);f<=track.indexAt(line.end);f++)peak=Math.max(peak,track.message(f).t.outRms);
  expect(peak).toBeGreaterThan(.001);
 }
 for(let i=0;i<track.frames;i++)expect(track.message(i).t.clock).toBeCloseTo(i/20,5);
});

