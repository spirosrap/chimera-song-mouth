test('both characters remain framed, deterministic and correctly disposed across cameras and seeks',()=>{
 const model=new VoiceModel(track.body,track.sampleRate),stage=new ArrivalField(model,track),update=spyOn(stage.head,'update');
 const movement=()=>{
  const values:number[]=[];stage.arms.group.traverseVisible(o=>{
   const mesh=o as THREE.Mesh<THREE.InstancedBufferGeometry>,a=mesh.geometry?.getAttribute('instanceStart');
   if(a)for(let i=0;i<mesh.geometry.instanceCount;i++)values.push(a.getX(i),a.getY(i),a.getZ(i));
  });return values;
 };
 try{
  stage.frame(23.4,false,0,'wide',0);
  for(const clothes of [stage.ianClothes,stage.louiseClothes]){
   let lowest=Infinity;clothes.group.traverseVisible(o=>{
    const mesh=o as THREE.Mesh<THREE.InstancedBufferGeometry>,a=mesh.geometry?.getAttribute('instanceStart');if(!a)return;
    for(let i=0;i<mesh.geometry.instanceCount;i++)lowest=Math.min(lowest,new THREE.Vector3().fromBufferAttribute(a,i).applyMatrix4(mesh.matrixWorld).y);
   });expect(lowest).toBeCloseTo(-6,5);
  }
  for(const [w,h] of [[1280,720],[375,211],[375,430]])for(const view of ['wide','ian','louise'] as CameraView[])for(const t of [6,23.4,27]){
   stage.resize(w,h);stage.frame(t,true,1,view,.5,'ian');
   expect(update.mock.calls.at(-1)![2]).toEqual(VoiceModel.articFromArray(track.message(track.indexAt(t)).t.artic));
   const before=movement();stage.frame(t,false,1,view,0);expect(movement()).toEqual(before);
   stage.frame(29,true,2,view,.5);stage.frame(t,true,3,view,.5);expect(movement()).toEqual(before);
   const objects=view==='wide'?[stage.head.scene,stage.listenerHead.scene]:view==='ian'?[stage.head.scene]:[stage.listenerHead.scene];let count=0,framed=true;
   for(const object of objects)object.traverseVisible(o=>{
    const mesh=o as THREE.Mesh<THREE.InstancedBufferGeometry>,a=mesh.geometry?.getAttribute('instanceStart');if(!a)return;
    for(let i=0;i<mesh.geometry.instanceCount;i++){
     const v=new THREE.Vector3().fromBufferAttribute(a,i).applyMatrix4(mesh.matrixWorld).project(stage.camera);count++;
     framed&&=[v.x,v.y,v.z].every(Number.isFinite)&&Math.abs(v.x)<.99&&Math.abs(v.y)<.99&&v.z<1;
    }
   });expect(count).toBeGreaterThan(1000);expect(framed).toBe(true);
  }
 }finally{
  update.mockRestore();let meshes=0,released=0;stage.scene.traverse(o=>{if(o instanceof THREE.Mesh){meshes++;o.geometry.addEventListener('dispose',()=>released++);}});
  const disposal=spyOn(VoiceModel.prototype,'dispose');stage.dispose();expect(disposal).toHaveBeenCalledTimes(1);disposal.mockRestore();model.dispose();
  expect(released).toBe(meshes);expect(stage.ianHair.group.parent).toBeNull();expect(stage.louiseHair.group.parent).toBeNull();
 }
});
